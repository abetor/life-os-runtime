def _action(
    action_id: str,
    *,
    actor: str,
    authority: str,
    target: str,
    access: str,
    effect_kind: str,
    artifact_commit: bool,
    retry_owner: str,
    rollback: str,
    crash_points: tuple[str, ...],
    irreversible: bool = False,
) -> dict[str, Any]:
    return {
        "action_id": action_id,
        "actor": actor,
        "authority": authority,
        "target": target,
        "access": access,
        "effect_kind": effect_kind,
        "artifact_commit": artifact_commit,
        "irreversible": irreversible,
        "crash_points": sorted(set(crash_points)),
        "retry_owner": retry_owner,
        "rollback": rollback,
    }


def _read(
    action_id: str,
    target: str,
    *,
    actor: str = "runtime",
    retry_owner: str = "runtime",
    rollback: str = "none-read-only",
) -> dict[str, Any]:
    return _action(
        action_id,
        actor=actor,
        authority="read",
        target=target,
        access="read",
        effect_kind="read-only",
        artifact_commit=False,
        retry_owner=retry_owner,
        rollback=rollback,
        crash_points=("during-bounded-read",),
    )


def _write(
    action_id: str,
    target: str,
    authority: str,
    *,
    actor: str = "runtime",
    effect_kind: str = "artifact-commit",
    retry_owner: str = "runtime",
    rollback: str = "reconcile-precondition-hash",
    crash_points: tuple[str, ...] = ("after-prepare-before-replace",),
    artifact_commit: bool = True,
) -> dict[str, Any]:
    return _action(
        action_id,
        actor=actor,
        authority=authority,
        target=target,
        access="write",
        effect_kind=effect_kind,
        artifact_commit=artifact_commit,
        retry_owner=retry_owner,
        rollback=rollback,
        crash_points=crash_points,
    )


def _invoke(
    action_id: str,
    target: str,
    authority: str,
    *,
    actor: str = "runtime",
    effect_kind: str = "connector-call",
    retry_owner: str = "runtime",
    rollback: str = "resume-from-registered-artifact",
    crash_points: tuple[str, ...] = ("after-tool-exit-before-artifact-registration",),
    irreversible: bool = False,
) -> dict[str, Any]:
    return _action(
        action_id,
        actor=actor,
        authority=authority,
        target=target,
        access="invoke",
        effect_kind=effect_kind,
        artifact_commit=False,
        retry_owner=retry_owner,
        rollback=rollback,
        crash_points=crash_points,
        irreversible=irreversible,
    )


def _flow(
    flow_id: str,
    *,
    actor: str,
    eval_class: str,
    authority_ceiling: str,
    reads: tuple[str, ...],
    actions: tuple[dict[str, Any], ...],
    retry_owner: str,
    rollback: str,
) -> dict[str, Any]:
    writes = sorted({a["target"] for a in actions if a["access"] == "write"})
    invokes = sorted({a["target"] for a in actions if a["access"] == "invoke"})
    crash_points = sorted({point for a in actions for point in a["crash_points"]})
    irreversible = sorted(
        f"{flow_id}/{a['action_id']}" for a in actions if a["irreversible"]
    )
    return {
        "flow_id": flow_id,
        "actor": actor,
        "eval_class": eval_class,
        "authority_ceiling": authority_ceiling,
        "allowed_reads": sorted(set(reads)),
        "allowed_writes": writes,
        "allowed_invocations": invokes,
        "irreversible_effects": irreversible,
        "crash_points": crash_points,
        "retry_owner": retry_owner,
        "rollback": rollback,
        "actions": list(actions),
    }


def _run_write(
    action_id: str = "record-run-state",
    *,
    actor: str = "runtime",
    retry_owner: str = "runtime",
) -> dict[str, Any]:
    return _write(
        action_id,
        "vault:agent/runs",
        "internal-write",
        actor=actor,
        effect_kind="run-state-commit",
        retry_owner=retry_owner,
        rollback="reconcile-run-envelope",
    )


def _proposal(
    action_id: str = "commit-review-proposal", *, actor: str = "runtime"
) -> dict[str, Any]:
    return _write(
        action_id,
        "vault:review",
        "proposal",
        actor=actor,
        effect_kind="proposal-commit",
        rollback="archive-or-supersede-proposal",
    )


